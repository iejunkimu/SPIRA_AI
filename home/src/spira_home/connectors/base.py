from typing import Protocol, AsyncIterator, Any
from spira_home.models import Capability, Observation, Receipt, Event


class Connector(Protocol):
    async def discover(self) -> list[Capability]: ...
    async def read(self, target: str) -> Observation: ...
    async def execute(self, target: str, desired: dict[str, Any], operation_id: str,
                      expected: dict[str, str] | None = None) -> Receipt: ...
    def events(self) -> AsyncIterator[Event]: ...
    async def close(self) -> None: ...


class Unavailable(Exception):
    pass
